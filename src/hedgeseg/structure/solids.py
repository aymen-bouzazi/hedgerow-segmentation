"""Supplementary windowed occupancy/mesh and ALS connectivity diagnostics.

These products reuse the photographic outlines. Marching cubes provides a
representation of the sampled occupancy grid, not a measured filled crown.
A 0.9 m proximity graph and its paths summarize assigned ALS observations;
they do not establish botanical branch architecture or leaf-off phenology.
The primary point and voxel comparisons retain the full native image domain.
"""

import numpy as np
import pandas as pd
from matplotlib.path import Path as MplPath
from scipy.sparse import coo_matrix
from scipy.sparse.csgraph import connected_components, dijkstra
from scipy.spatial import cKDTree
from skimage.measure import marching_cubes

from ..evaluation.context import projected_frames, reference_inputs, result_root
from ..io import ROOT, clouds, config, inventory, labels, write_json


def mesh(mask, lo, cell, path):
    """Marching-cubes surface of an occupied-voxel grid (display/diagnostic only)."""
    if mask.sum() < 40:
        return 0, 0
    v, f, _, _ = marching_cubes(np.pad(mask.astype(np.float32), 1), 0.5, spacing=(cell,) * 3)
    v += (lo - 0.5) * cell
    with path.open("w") as out:
        out.write(
            f"ply\nformat ascii 1.0\ncomment stem-relative XY and world Z minus stem ground, metres\nelement vertex {len(v)}\nproperty float x\nproperty float y\nproperty float z\nelement face {len(f)}\nproperty list uchar int vertex_indices\nend_header\n"
        )
        np.savetxt(out, v, fmt="%.5f")
        np.savetxt(out, np.c_[np.full(len(f), 3), f], fmt="%d")
    return len(v), len(f)


def framework(points, base, link):
    """Summary of the 0.9 m proximity graph of one tree's ALS points."""
    tree = cKDTree(points)
    nn = tree.query(points, k=2)[0][:, 1]
    pairs = tree.query_pairs(link, output_type="ndarray")
    n = len(points)
    w = np.linalg.norm(points[pairs[:, 0]] - points[pairs[:, 1]], axis=1)
    graph = coo_matrix(
        (np.r_[w, w], (np.r_[pairs[:, 0], pairs[:, 1]], np.r_[pairs[:, 1], pairs[:, 0]])),
        shape=(n, n),
    ).tocsr()
    ncomp, _ = connected_components(graph, directed=False)
    distance, parent = dijkstra(graph, indices=base, directed=False, return_predecessors=True)
    return distance, parent, int(ncomp), float(np.median(nn))


def run(review_path=None, output_dir=None):
    """Stage ``solids``: windowed occupancy meshes and ALS connectivity diagnostics."""
    cfg = config()
    d = clouds()
    inv = inventory().set_index("gpsID")
    L = labels()
    lab = L["Hybrid"]
    alslab = np.load(ROOT / "data/working/hybrid_labels.npz")["hybrid_als_label"]
    dest = result_root(output_dir)
    assets = dest / "structure"
    assets.mkdir(exist_ok=True)
    # These patterns are generated by this stage. A changed review must not leave
    # an obsolete mesh in the current output folder or inflate export receipts.
    for pattern in [
        "ID_*_outline_occupied_cells.ply",
        "ID_*_Hybrid_occupied_cells.ply",
        "ID_*_ALS_connectivity.csv",
    ]:
        for old in assets.glob(pattern):
            old.unlink()
    cell = cfg.get("occupancy_voxel_m", 0.25)
    link = cfg.get("als_framework_link_m", 0.9)
    _, cams, aa, receipt = reference_inputs(review_path)
    references = {}
    for pid, c, uv, depth, domain, outlines in projected_frames(d["uav_xyz"], cams, aa):
        for a in outlines:
            inside = domain & MplPath(np.asarray(a["uv"], float)).contains_points(uv)
            if inside.sum() >= 20:
                references[a["gpsID"]] = (inside, domain, pid)
    rows = []
    for g, t in inv.iterrows():
        stem = t[["x", "y"]].to_numpy(float)
        gz = t.ground_z
        rec = dict(
            gpsID=g,
            method="Hybrid",
            stratum=t.stratum,
            solid_iou=np.nan,
            note="no primary outline" if g not in references else "",
        )
        if g in references:
            inside, domain, pid = references[g]
            pred = (lab == g) & domain
            xyz = d["uav_xyz"]
            idx = np.flatnonzero(inside | pred)
            if len(idx):
                local = xyz[idx] - np.r_[stem, gz]
                key = np.floor(local / cell).astype(int)
                lo = key.min(axis=0)
                shape = key.max(axis=0) - lo + 1
                if np.prod(shape) <= 8000000:
                    k = key - lo
                    ref = np.zeros(shape, bool)
                    mine = np.zeros(shape, bool)
                    ref[tuple(k[inside[idx]].T)] = True
                    mine[tuple(k[pred[idx]].T)] = True
                    rv = ref.sum() * cell**3
                    mv = mine.sum() * cell**3
                    nr, nf = mesh(ref, lo, cell, assets / f"ID_{g:03d}_outline_occupied_cells.ply")
                    npv, npf = mesh(
                        mine, lo, cell, assets / f"ID_{g:03d}_Hybrid_occupied_cells.ply"
                    )
                    rec.update(
                        photo_id=pid,
                        reference_volume_m3=rv,
                        method_volume_m3=mv,
                        volume_ratio=mv / rv if rv else np.nan,
                        solid_iou=(ref & mine).sum() / (ref | mine).sum(),
                        ref_vertices=nr,
                        ref_faces=nf,
                        method_vertices=npv,
                        method_faces=npf,
                    )
                else:
                    rec["note"] = "sparse extent exceeds dense-grid guard; volume not fabricated"
        idx = np.flatnonzero(alslab == g)
        rec["als_returns_own"] = len(idx)
        rec["als_skeleton_nodes"] = 0
        if len(idx) >= 12:
            p = d["als_xyz"][idx] - np.r_[stem, gz]
            base = int(np.argmin(np.linalg.norm(p, axis=1)))
            distance, parent, ncomp, spacing = framework(p, base, link)
            reached = np.isfinite(distance)
            frame = pd.DataFrame(
                dict(
                    source_point_index=idx,
                    local_x_m=p[:, 0],
                    local_y_m=p[:, 1],
                    height_from_stem_ground_m=p[:, 2],
                    reachable=reached,
                    path_distance_m=distance,
                    parent_node_index=parent,
                )
            )
            frame.to_csv(assets / f"ID_{g:03d}_ALS_connectivity.csv", index=False)
            rec.update(
                als_skeleton_nodes=int(reached.sum()),
                als_fraction=float(reached.mean()),
                als_components=ncomp,
                als_nn_spacing_m=spacing,
                als_longest_path_m=float(distance[reached].max()),
            )
        rows.append(rec)
    x = pd.DataFrame(rows)
    x.to_csv(dest / "tables/solids.csv", index=False)
    write_json(
        dest / "qa/solids.json",
        dict(
            method="Hybrid",
            grid_m=cell,
            link_m=link,
            trees_with_solids=int(x.solid_iou.notna().sum()),
            median_solid_iou=float(x.solid_iou.median()),
            trees_with_als_framework=int((x.als_skeleton_nodes > 0).sum()),
            actual_mesh_files=len(list(assets.glob("*.ply"))),
            actual_graph_files=len(list(assets.glob("*connectivity.csv"))),
            coordinate_frame="stem-relative projected XY; world Z minus stem-local ground",
            reference="in-frame cloud cells intersecting the same photograph outline; not independent depth validation",
            skeleton_status="inferred ALS proximity connectivity; not measured branch architecture",
            review_inputs=receipt,
        ),
    )
    print(
        f"Exported {len(list(assets.glob('*.ply')))} occupied-cell meshes and {len(list(assets.glob('*connectivity.csv')))} ALS connectivity graphs",
        flush=True,
    )
