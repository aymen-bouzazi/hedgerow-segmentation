"""Regenerate docs/FUNCTIONS.md from the docstrings:  python tools/make_function_index.py"""

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SEG = [
    "constants",
    "scoring",
    "seeds",
    "stem_paths",
    "canopy_peaks",
    "height",
    "transfer",
    "combine",
    "baselines",
    "methods",
    "pipeline",
]
ORDER = [
    "io.py",
    "prepare.py",
    *[f"segmentation/{m}.py" for m in SEG],
    "evaluation",
    "structure",
    "viewers",
    "cameras",
    "checks.py",
]


def first_paragraph(doc):
    return " ".join(doc.strip().split("\n\n")[0].split()) if doc else "-"


def files():
    pkg = ROOT / "src" / "hedgeseg"
    for item in ORDER:
        path = pkg / item
        yield from (sorted(path.glob("*.py")) if path.is_dir() else [path])


lines = [
    "# Function reference",
    "",
    "Every module and public function of `src/hedgeseg`, with a link to its source line.",
    "Generated by `python tools/make_function_index.py` from the docstrings; do not edit by hand.",
    "For the scientific meaning of each step read [METHODS.md](METHODS.md).",
    "",
]
for path in files():
    rel = path.relative_to(ROOT).as_posix()
    tree = ast.parse(path.read_text())
    if path.name == "__init__.py" and not any(isinstance(n, ast.FunctionDef) for n in tree.body):
        continue
    lines += [f"## [`{rel}`](../{rel})", "", first_paragraph(ast.get_docstring(tree)), ""]
    rows = [
        n
        for n in tree.body
        if isinstance(n, (ast.FunctionDef, ast.ClassDef)) and not n.name.startswith("__")
    ]
    if rows:
        lines += ["| function | what it does |", "|---|---|"]
        for n in rows:
            args = ", ".join(a.arg for a in n.args.args) if isinstance(n, ast.FunctionDef) else ""
            sig = f"{n.name}({args})" if isinstance(n, ast.FunctionDef) else f"class {n.name}"
            lines.append(
                f"| [`{sig}`](../{rel}#L{n.lineno}) | {first_paragraph(ast.get_docstring(n))} |"
            )
        lines.append("")
(ROOT / "docs" / "FUNCTIONS.md").write_text("\n".join(lines) + "\n")
print("docs/FUNCTIONS.md written")
